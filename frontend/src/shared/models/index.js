/**
 * Data models. They mirror the JSON that Laravel API Resources will return, so the UI never
 * depends on mock-only shapes. Collections come back as { data: [...], meta: {...} }.
 *
 * @typedef {Object} User
 * @property {number} id
 * @property {string} name
 * @property {string} username
 * @property {string} email
 * @property {string|null} avatar_url
 * @property {string|null} about
 * @property {'ar'|'en'} locale                  // GET /api/user -> locale; PUT /api/user/preferences
 * @property {boolean} is_online
 * @property {string|null} last_seen_at          // ISO 8601
 *
 * @typedef {Object} Conversation
 * @property {number} id
 * @property {'private'|'group'} type
 * @property {string|null} name                  // groups only
 * @property {string|null} avatar_url
 * @property {number[]} participant_ids
 * @property {Message|null} last_message
 * @property {number} unread_count
 * @property {boolean} is_pinned
 * @property {boolean} is_muted
 * @property {boolean} is_archived
 * @property {string|null} draft
 * @property {string} updated_at
 *
 * @typedef {Object} Message
 * @property {number|string} id                  // string while optimistic (client_id)
 * @property {string} [client_id]                // idempotency key generated by the client
 * @property {number} conversation_id
 * @property {number} sender_id
 * @property {string|null} body
 * @property {'text'|'image'|'video'|'audio'|'voice'|'file'|'location'|'contact'|'poll'|'system'} type
 * @property {number|null} reply_to_id
 * @property {string} created_at
 * @property {string|null} updated_at
 * @property {string|null} delivered_at
 * @property {string|null} read_at
 * @property {string|null} deleted_at
 * @property {MessageAttachment[]} attachments
 * @property {Reaction[]} reactions
 *
 * @typedef {Object} MessageAttachment
 * @property {number} id @property {string} name @property {string} mime
 * @property {number} size @property {string} url @property {number|null} [duration] @property {number[]|null} [waveform]
 *
 * @typedef {Object} Reaction
 * @property {string} emoji @property {number[]} user_ids
 *
 * @typedef {Object} Notification
 * @property {number} id @property {string} type @property {string} body @property {string|null} read_at @property {string} created_at
 */

export const MESSAGE_TYPES = ['text', 'image', 'video', 'audio', 'voice', 'file', 'location', 'contact', 'poll', 'system'];
export const REACTIONS = ['❤️', '😂', '👍', '😢', '😮', '🔥'];
export const CONVERSATION_FILTERS = ['all', 'unread', 'groups', 'contacts', 'archived'];
